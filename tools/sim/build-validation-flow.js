#!/usr/bin/env node
/* Builds a Node-RED tab that replays the validation scenarios inside a running
 * Node-RED: function nodes generate the simulated signals (the same generators
 * as tools/sim/validate.js, embedded as source), the real nodes analyse them,
 * and a checker per scenario reports pass / fail to a debug node.
 *
 *   node tools/sim/build-validation-flow.js > /tmp/validation-flow.json
 *   curl -X POST http://localhost:1890/flow -H 'Content-Type: application/json' \
 *        --data-binary @/tmp/validation-flow.json          # adds the tab
 *
 * Press the inject buttons (or POST /inject/<id>); each scenario answers with
 * one message `{ test, pass, detail }` in the debug sidebar and sets the status
 * of its checker node.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const lib = require("./validate-lib");

// The generators, as source text a function node can evaluate
const signalsSource = fs
    .readFileSync(path.join(__dirname, "signals.js"), "utf8")
    .replace(/^"use strict";\s*$/m, "")
    .replace(/module\.exports = [^\n]*\n?/, "");
const GENERATORS =
    "const sig = (function () {\n" +
    signalsSource +
    "\nreturn { rng, bearingSignal, faultFreqs, GEOMETRY };\n})();\n" +
    "const rng = sig.rng;\n" +
    ["processSignal", "injectFault", "pumpSignals", "degradation", "gearSignal"]
        .map((name) => "const " + name + " = " + lib[name].toString() + ";")
        .join("\n") +
    "\n";

const TAB = "val_tab";
const nodes = [
    {
        id: TAB,
        type: "tab",
        label: "🔬 validation (simulated)",
        info: "Replays tools/sim/validate.js scenarios through the real nodes. Generated by tools/sim/build-validation-flow.js."
    },
    {
        id: "val_debug",
        type: "debug",
        z: TAB,
        name: "result",
        active: true,
        tosidebar: true,
        complete: "payload",
        x: 1010,
        y: 40,
        wires: []
    }
];
let row = 0;
const injectIds = [];

/**
 * One scenario: inject -> generator (function) -> node under test -> checker (function) -> debug.
 * `gen` is the body of the generator function node (GENERATORS is prepended), it
 * returns one message or [[messages…]]; `check` is the body of the checker, which
 * sees every output of the node and returns { pass, detail } on `msg.vLast`.
 */
function scenario(name, nodeConfig, gen, check) {
    const y = 100 + 60 * row;
    const id = "val_" + row++;
    injectIds.push({ id: id + "_i", name: name });
    nodes.push(
        {
            id: id + "_i",
            type: "inject",
            z: TAB,
            name: name,
            props: [],
            repeat: "",
            once: false,
            x: 170,
            y: y,
            wires: [[id + "_g"]]
        },
        {
            id: id + "_g",
            type: "function",
            z: TAB,
            name: "simulate",
            func: GENERATORS + gen,
            outputs: 1,
            x: 400,
            y: y,
            wires: [[id + "_n"]]
        },
        Object.assign({ id: id + "_n", z: TAB, name: "", x: 600, y: y, wires: [[id + "_c"], [id + "_c"]] }, nodeConfig),
        {
            id: id + "_c",
            type: "function",
            z: TAB,
            name: "check",
            func:
                "const all = context.get('all') || [];\nall.push(msg);\ncontext.set('all', all);\n" +
                "if (!msg.vLast) return null;\ncontext.set('all', []);\n" +
                "const r = (function (all, last) {\n" +
                check +
                "\n})(all, msg);\n" +
                "node.status({ fill: r.pass ? 'green' : 'red', shape: 'dot', text: (r.pass ? 'PASS ' : 'FAIL ') + r.detail });\n" +
                "return { payload: { test: " +
                JSON.stringify(name) +
                ", pass: r.pass, detail: r.detail } };",
            outputs: 1,
            x: 810,
            y: y,
            wires: [["val_debug"]]
        }
    );
}

// ---------------------------------------------------------------- bearings
const bearingNode = {
    type: "signal-analyzer",
    mode: "envelope",
    fftSize: 32768,
    samplingRate: 20000,
    envelopeBandLow: 2000,
    envelopeBandHigh: 6000,
    bearingBalls: 9,
    bearingBallDiameter: 7.94,
    bearingPitchDiameter: 39.04,
    bearingContactAngle: 0
};
const bearingGen = (extra) =>
    "const rpm = 1500, ff = sig.faultFreqs(rpm / 60);\n" +
    "const p = Object.assign({ fs: 20000, n: 32768, seed: 42, shaftHz: rpm / 60, noiseG: 0.05, unbalanceG: 0.05 }, " +
    extra +
    ");\nreturn { payload: sig.bearingSignal(p), rpm: rpm, vLast: true };";
const bearingCheck = (expected) =>
    "const f = last.bearingFaults || [];\n" +
    "const types = Array.from(new Set(f.filter((x) => !x.coincidesWith1X).map((x) => x.type)));\n" +
    "const want = " +
    JSON.stringify(expected) +
    ";\nconst pass = want === null ? f.length === 0 : types.some((t) => t === want) && !types.some((t) => ['BPFO','BPFI','BSF'].includes(t) && t !== want);\n" +
    "return { pass: pass, detail: (f.length ? types.join('+') : 'no fault lines') + ' (expected ' + (want || 'none') + ')' };";

scenario("bearing: healthy", bearingNode, bearingGen("{}"), bearingCheck(null));
scenario(
    "bearing: outer race defect",
    bearingNode,
    bearingGen("{ faultHz: ff.BPFO, impactG: 0.2 }"),
    bearingCheck("BPFO")
);
scenario(
    "bearing: inner race defect",
    bearingNode,
    bearingGen("{ faultHz: ff.BPFI, impactG: 0.2, loadModulation: 0.8 }"),
    bearingCheck("BPFI")
);
scenario(
    "bearing: ball defect",
    bearingNode,
    bearingGen("{ faultHz: 2 * ff.BSF, impactG: 0.2, loadModulation: 0.5, modulationHz: ff.FTF }"),
    bearingCheck("BSF")
);
scenario("bearing: looseness", bearingNode, bearingGen("{ loosenessG: 0.6 }"), bearingCheck("Looseness"));

// -------------------------------------------------------------------- gears
const gearNode = {
    type: "signal-analyzer",
    mode: "cepstrum",
    fftSize: 16384,
    samplingRate: 20000,
    gearToothCount: "23"
};
const gearGen = (damage) =>
    "return { payload: gearSignal({ seed: 7, shaftHz: 25, damage: " + damage + " }), rpm: 1500, vLast: true };";
scenario(
    "gear: healthy mesh",
    gearNode,
    gearGen(0),
    "const ser = last.gears[0].sidebandEnergyRatio;\nreturn { pass: last.hasFault === false && ser < 0.1, detail: 'SER ' + ser.toFixed(2) + ', no fault' };"
);
scenario(
    "gear: severe damage",
    gearNode,
    gearGen(1.2),
    "const ser = last.gears[0].sidebandEnergyRatio;\nreturn { pass: last.hasFault === true && ser > 1, detail: 'SER ' + ser.toFixed(2) + ', ' + (last.gearFaults[0] || {}).type };"
);

// ---------------------------------------------------------------------- ISO
scenario(
    "ISO 20816: 4.0 mm/s from an accelerometer",
    {
        type: "signal-analyzer",
        mode: "vibration",
        windowSize: 8192,
        samplingRate: 10000,
        vibInputUnit: "g",
        iso10816Class: "group2_rigid"
    },
    // one 25 Hz line of 4.0 mm/s RMS plus a 3 kHz bearing tone that carries no velocity
    "const fs = 10000, n = 8192, w = 2 * Math.PI * 25, r = rng(3), x = [];\n" +
        "for (let i = 0; i < n; i++) { const t = i / fs;\n" +
        "  x.push(((0.004 * Math.SQRT2 * w * Math.cos(w * t) + 4 * Math.sin(2 * Math.PI * 3000 * t)) / 9.80665) + 0.02 * r.normal()); }\n" +
        "return { payload: x, rpm: 1500, vLast: true };",
    "const iso = last.payload.iso20816;\nreturn { pass: Math.abs(iso.rmsVelocity - 4.0) < 0.2 && iso.zone === 'C', detail: iso.rmsVelocity.toFixed(2) + ' mm/s, zone ' + iso.zone + ' (' + iso.conversion + ')' };"
);

// ------------------------------------------------------------------ streams
const streamOf = (expr) =>
    "const values = " +
    expr +
    ";\nreturn [values.map((v, i) => Object.assign({ vLast: i === values.length - 1 }, v))];";

scenario(
    "anomaly: 3σ step in a noisy process value",
    {
        type: "anomaly-detector",
        method: "zscore",
        windowSize: 200,
        zscoreThreshold: 3,
        zscoreWarning: 2,
        hysteresisEnabled: false
    },
    streamOf("injectFault(processSignal({ seed: 5, n: 2100 }), 'step', 2000, 0.5, 5).y.map((v) => ({ payload: v }))"),
    // the step sits 100 samples before the end of the stream
    "const n = all.length, crit = (m) => m.severity === 'critical';\n" +
        "const before = all.slice(0, n - 100).filter(crit).length, after = all.slice(n - 100, n - 80).filter(crit).length;\n" +
        "return { pass: after >= 1 && before / (n - 100) < 0.02, detail: after + ' critical in the 20 samples after the step, ' + before + ' false in ' + (n - 100) };"
);

scenario(
    "RUL: accelerating wear, exponential model",
    {
        type: "trend-predictor",
        mode: "rul",
        windowSize: 200,
        failureThreshold: 10,
        rulUnit: "minutes",
        degradationModel: "exponential"
    },
    streamOf(
        "degradation({ shape: 'exponential', seed: 4 }).samples.filter((s) => s.tMin <= 2250).map((s) => ({ payload: s.value, timestamp: Math.round(s.tMin * 60000), tMin: s.tMin }))"
    ),
    // at 75 % of a 3000 min life, 750 min remain
    "const rul = last.rul, truth = 3000 - last.tMin, err = (rul.value - truth) / truth;\n" +
        "return { pass: Math.abs(err) < 0.15, detail: rul.value.toFixed(0) + ' min predicted, ' + truth.toFixed(0) + ' true (' + (100 * err).toFixed(0) + ' %), band ' + rul.lower.toFixed(0) + '-' + rul.upper.toFixed(0) };"
);

scenario(
    "PCA: pressure sensor reads 6 % high",
    { type: "pca-anomaly", method: "combined", windowSize: 1000, threshold: 3, varianceThreshold: 0.999 },
    streamOf(
        "pumpSignals({ seed: 2, n: 2000 }).map((r, i) => ({ payload: { flow: Math.log(r.flow), pressure: Math.log(r.pressure * (i >= 1700 ? 1.06 : 1)), power: Math.log(r.power), temperature: r.temperature } }))"
    ),
    "const n = all.length, an = (m) => m.isAnomaly === true;\n" +
        "const faulty = all.slice(n - 300), healthy = all.slice(0, n - 300).filter((m) => m.isAnomaly !== undefined);\n" +
        "const hit = faulty.filter(an), named = hit.filter((m) => m.topContributor === 'pressure').length, fa = healthy.filter(an).length;\n" +
        "return { pass: hit.length / 300 > 0.9 && named / Math.max(1, hit.length) > 0.8 && fa / Math.max(1, healthy.length) < 0.08,\n" +
        "  detail: hit.length + '/300 faulty samples flagged, ' + named + ' name pressure, ' + fa + ' false in ' + healthy.length };"
);

process.stdout.write(
    JSON.stringify({ id: TAB, label: nodes[0].label, info: nodes[0].info, nodes: nodes.slice(1) }, null, 1)
);
process.stderr.write(injectIds.map((i) => i.id + "  " + i.name).join("\n") + "\n");
